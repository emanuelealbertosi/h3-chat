import assert from 'node:assert/strict';
import {imageModelOptions} from '../ui/image-model-options.js';
import {imageRequestValues} from '../ui/image-request.js';
const controls=imageModelOptions({architecture:'fibo2'},{});
assert.deepEqual(controls,{grid:16,max:2048,samplers:['auto','euler'],schedulers:['auto','simple']});
const model={id:'fibo',architecture:'fibo2',engine:'fibo2',width:1024,height:1024,steps:50,cfg:5,sampler:'euler',scheduler:'simple',strength:1};
const state={models:[model],settings:{image_overrides:{fibo:{aspect:'16:9',megapixels:1,seed:42}},seed:-1}};
const value=imageRequestValues(state,{image_model:'fibo'});
assert.equal(value.width%16,0);assert.equal(value.height%16,0);assert.equal(value.steps,50);assert.equal(value.cfg,5);assert.equal(value.seed,42);assert.ok(value.width>value.height);
assert.equal(imageModelOptions({architecture:'moss'},{samplers:[],schedulers:[]}).grid,1);
console.log('FIBO grid, available samplers, aspect, megapixels and saved seed passed.');
